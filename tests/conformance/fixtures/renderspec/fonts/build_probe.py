"""Build the tiny TrueType fixture the font-embedding tests register.

The committed `probe.ttf` is generated by this script so the bytes are
explainable rather than a mystery binary:

    python tests/conformance/fixtures/renderspec/fonts/build_probe.py

It carries five glyphs — `.notdef`, `space`, `A`, `B` and `ü` — so the tests can
check glyph mapping, missing characters, WinAnsi text and composite-free
subsetting without depending on a system font. The tables are the minimum a
TrueType-outline program needs, and every timestamp is zero so the fixture
itself cannot make an artifact vary.
"""

from __future__ import annotations

import struct
from pathlib import Path

UPEM = 1000
ADVANCES = (500, 250, 600, 600, 550)
GLYPHS: list[list[list[tuple[int, int]]]] = [
    [],  # .notdef
    [],  # space
    [[(0, 0), (300, 700), (600, 0)]],  # A
    [[(50, 0), (550, 0), (550, 700), (50, 700)]],  # B
    [[(50, 0), (500, 0), (500, 700), (50, 700)]],  # ü
]
CMAP = {" ": 1, "A": 2, "B": 3, "ü": 4}


def _checksum(data: bytes) -> int:
    padded = data + b"\0" * (-len(data) % 4)
    return sum(struct.unpack(f">{len(padded) // 4}I", padded)) & 0xFFFFFFFF


def _glyph(contours: list[list[tuple[int, int]]]) -> bytes:
    if not contours:
        return b""
    points = [point for contour in contours for point in contour]
    xs = [point[0] for point in points]
    ys = [point[1] for point in points]
    data = struct.pack(">h4h", len(contours), min(xs), min(ys), max(xs), max(ys))
    end = -1
    for contour in contours:
        end += len(contour)
        data += struct.pack(">H", end)
    data += struct.pack(">H", 0)  # no instructions
    data += bytes([0x01] * len(points))  # on-curve, 16-bit deltas
    previous = 0
    for x in xs:
        data += struct.pack(">h", x - previous)
        previous = x
    previous = 0
    for y in ys:
        data += struct.pack(">h", y - previous)
        previous = y
    return data


def _signed16(value: int) -> int:
    """One modular delta as the int16 `idDelta` field stores it."""

    return (value + 0x8000) % 0x10000 - 0x8000


def _cmap() -> bytes:
    segments = sorted((ord(character), gid) for character, gid in CMAP.items())
    count = len(segments) + 1
    entry_selector = max(count.bit_length() - 1, 0)
    search_range = 2 * (1 << entry_selector)
    subtable = (
        struct.pack(
            ">7H", 4, 0, 0, 2 * count, search_range, entry_selector, 2 * count - search_range
        )
        + b"".join(struct.pack(">H", code) for code, _gid in segments)
        + struct.pack(">H", 0xFFFF)
        + b"\0\0"
        + b"".join(struct.pack(">H", code) for code, _gid in segments)
        + struct.pack(">H", 0xFFFF)
        + b"".join(struct.pack(">h", _signed16(gid - code)) for code, gid in segments)
        + struct.pack(">h", 1)
        + b"\0\0" * count
    )
    subtable = subtable[:2] + struct.pack(">H", len(subtable)) + subtable[4:]
    return struct.pack(">HHHH", 0, 1, 3, 1) + struct.pack(">I", 12) + subtable


def _name() -> bytes:
    entries = [
        (1, "Probe Sans"),
        (2, "Regular"),
        (4, "Probe Sans Regular"),
        (6, "ProbeSans-Regular"),
    ]
    strings = b""
    records = b""
    for name_id, text in entries:
        encoded = text.encode("utf-16-be")
        records += struct.pack(">HHHHHH", 3, 1, 0x409, name_id, len(encoded), len(strings))
        strings += encoded
    return struct.pack(">HHH", 0, len(entries), 6 + 12 * len(entries)) + records + strings


def build() -> bytes:
    glyf = b""
    loca = [0]
    for contours in GLYPHS:
        glyf += _glyph(contours)
        glyf += b"\0" * (-len(glyf) % 4)
        loca.append(len(glyf))

    head = struct.pack(
        ">IIIIHHqqhhhhHHhhh",
        0x00010000,
        0x00010000,
        0,  # checkSumAdjustment, patched on assembly
        0x5F0F3CF5,
        3,  # flags
        UPEM,
        0,
        0,  # created, modified: zero keeps the fixture deterministic
        0,
        0,
        600,
        700,
        0,  # macStyle
        8,  # lowestRecPPEM
        2,  # fontDirectionHint
        1,  # indexToLocFormat (long offsets)
        0,  # glyphDataFormat
    )
    hhea = struct.pack(
        ">IhhhHhhhhhhhhhhhH",
        0x00010000,
        800,
        -200,
        0,
        600,
        0,
        0,
        600,
        1,  # caretSlopeRise
        0,  # caretSlopeRun
        0,  # caretOffset
        0,
        0,
        0,
        0,  # reserved
        0,  # metricDataFormat
        len(GLYPHS),
    )
    maxp = struct.pack(
        ">IHHHHHHHHHHHHHH", 0x00010000, len(GLYPHS), 4, 1, 0, 0, 2, 0, 0, 0, 0, 0, 0, 0, 0
    )
    hmtx = b"".join(struct.pack(">Hh", advance, 0) for advance in ADVANCES)
    post = struct.pack(">IIhhIIIII", 0x00030000, 0, -100, 50, 0, 0, 0, 0, 0)
    os2 = struct.pack(
        ">HhHHHhhhhhhhhhhh10sIIII4sHHHhhhHHIIhhHHH",
        4,
        600,
        400,
        5,
        0,
        650,
        600,
        0,
        75,
        650,
        600,
        0,
        350,
        50,
        250,
        0,
        b"\0" * 10,
        1,
        0,
        0,
        0,
        b"NONE",
        0x0040,
        0x20,
        0xFC,
        800,
        -200,
        0,
        800,
        200,
        1,
        0,
        500,
        700,
        0,
        32,
        1,
    )

    tables = {
        "OS/2": os2,
        "cmap": _cmap(),
        "glyf": glyf,
        "head": head,
        "hhea": hhea,
        "hmtx": hmtx,
        "loca": struct.pack(f">{len(loca)}I", *loca),
        "maxp": maxp,
        "name": _name(),
        "post": post,
    }

    ordered = sorted(tables.items())
    count = len(ordered)
    entry_selector = max(count.bit_length() - 1, 0)
    search_range = 16 * (1 << entry_selector)
    program = bytearray(
        struct.pack(
            ">4sHHHH",
            b"\x00\x01\x00\x00",
            count,
            search_range,
            entry_selector,
            16 * count - search_range,
        )
    )
    offset = 12 + 16 * count
    records = bytearray()
    body = bytearray()
    for tag, data in ordered:
        padded = data + b"\0" * (-len(data) % 4)
        records += struct.pack(">4sIII", tag.encode("latin-1"), _checksum(data), offset, len(data))
        body += padded
        offset += len(padded)
    program += records + body

    head_offset = (
        12 + 16 * count + sum(len(data) + (-len(data) % 4) for tag, data in ordered if tag < "head")
    )
    struct.pack_into(">I", program, 8, 0)
    adjustment = (0xB1B0AFBA - _checksum(bytes(program))) & 0xFFFFFFFF
    struct.pack_into(">I", program, head_offset + 8, adjustment)
    return bytes(program)


if __name__ == "__main__":
    target = Path(__file__).with_name("probe.ttf")
    target.write_bytes(build())
    print(f"wrote {target} ({target.stat().st_size} bytes)")
